function changeLanguage(lang) {
    // Update active button classes
    const allBtns = ['lang-en', 'lang-fr', 'lang-en-mobile', 'lang-fr-mobile'];
    allBtns.forEach(id => {
        const btn = document.getElementById(id);
        if(btn) {
            btn.classList.remove('text-brand-orange', 'font-bold');
            btn.classList.add('text-slate-400');
        }
    });
    
    // Set active class
    const desktopBtn = document.getElementById(`lang-${lang}`);
    const mobileBtn = document.getElementById(`lang-${lang}-mobile`);
    if(desktopBtn) {
        desktopBtn.classList.add('text-brand-orange', 'font-bold');
        desktopBtn.classList.remove('text-slate-400');
    }
    if(mobileBtn) {
        mobileBtn.classList.add('text-brand-orange', 'font-bold');
        mobileBtn.classList.remove('text-slate-400');
    }
    
    // Save preference
    localStorage.setItem('logibridge_lang', lang);
    
    // Update text content
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            // Need to carefully update text without breaking child elements (like icons)
            // It's safer to use a span inside elements if they contain icons.
            // But for simple texts, innerText/innerHTML is fine.
            // If the element has child nodes (like an icon), we only replace text nodes that aren't empty
            const hasIcon = element.querySelector('i');
            if(hasIcon) {
                // Find purely text nodes
                for(let i = 0; i < element.childNodes.length; i++) {
                    const node = element.childNodes[i];
                    if(node.nodeType === 3 && node.nodeValue.trim() !== '') {
                        node.nodeValue = " " + translations[lang][key] + " ";
                        break;
                    }
                }
            } else {
                element.innerHTML = translations[lang][key];
            }
        }
    });
    
    // Special handling for HTML strings like "Your Bridge To <span class='gradient-text'>The World</span>"
    // is already handled by splitting keys up in the data-i18n logic.
}

document.addEventListener('DOMContentLoaded', () => {
    // Default to English unless French is saved
    const savedLang = localStorage.getItem('logibridge_lang') || 'en';
    changeLanguage(savedLang);
});
